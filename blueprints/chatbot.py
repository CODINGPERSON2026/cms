@chatbot_bp.route("/graph-view", methods=["GET"])
@require_chatbot_access
def graph_view():
    """Renders standalone page containing full-screen interactive graph with export & zoom controls."""
    session_id = request.args.get("session_id") or session.get("user_id") or "default_user"
    cached = ConversationMemory.get_dataset(session_id)
    chart_data = cached.get("chart_data") or {}
    user_question = cached.get("user_question") or "CMS Inventory Analysis"

    return render_template(
        "standalone_graph.html",
        session_id=session_id,
        chart_data=json.dumps(chart_data),
        title=user_question,
        records=cached.get("records", []),
        columns=cached.get("columns", [])
    )


