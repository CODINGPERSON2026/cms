@chatbot_bp.route("/export-data", methods=["GET"])
@csrf.exempt
def export_data():
    """Generates file download for CSV, Excel, or PDF report from session dataset."""
    session_id = request.args.get("session_id") or session.get("user_id") or "default_user"
    fmt = (request.args.get("format") or "csv").lower()

    cached = ConversationMemory.get_dataset(session_id)
    records = cached.get("records", [])
    columns = cached.get("columns", [])

    if not records:
        return jsonify({"success": False, "message": "No session dataset found to export."}), 404

    if not columns and records:
        columns = list(records[0].keys())

    if fmt == "csv":
        output = io.StringIO()
        writer = csv.DictWriter(output, fieldnames=columns)
        writer.writeheader()
        for row in records:
            writer.writerow(row)

        mem = io.BytesIO()
        mem.write(output.getvalue().encode("utf-8"))
        mem.seek(0)
        return send_file(
            mem,
            mimetype="text/csv",
            as_attachment=True,
            download_name=f"cms_export_{session_id}.csv"
        )

    elif fmt in ("excel", "xlsx"):
        # Format as tab-separated spreadsheet or CSV compatible stream
        output = io.StringIO()
        writer = csv.writer(output, delimiter="\t")
        writer.writerow(columns)
        for row in records:
            writer.writerow([row.get(col, "") for col in columns])

        mem = io.BytesIO()
        mem.write(output.getvalue().encode("utf-8"))
        mem.seek(0)
        return send_file(
            mem,
            mimetype="application/vnd.ms-excel",
            as_attachment=True,
            download_name=f"cms_export_{session_id}.xls"
        )

    elif fmt == "pdf":
        # Generate clean HTML printable document as attachment
        title = cached.get("user_question") or "CMS Data Analysis Report"
        html_content = f"""<!DOCTYPE html>
<html>
<head>
    <title>{title}</title>
    <style>
        body {{ font-family: Arial, sans-serif; margin: 20px; color: #333; }}
        h2 {{ color: #1e293b; border-bottom: 2px solid #3b82f6; padding-bottom: 8px; }}
        table {{ width: 100%; border-collapse: collapse; margin-top: 15px; font-size: 12px; }}
        th, td {{ border: 1px solid #cbd5e1; padding: 8px; text-align: left; }}
        th {{ background-color: #0f172a; color: white; }}
        tr:nth-child(even) {{ background-color: #f8fafc; }}
        .footer {{ margin-top: 30px; font-size: 10px; color: #64748b; text-align: center; }}
    </style>
</head>
<body>
    <h2>{title}</h2>
    <p>Generated by CMS AI Assistant • Total Rows: {len(records)}</p>
    <table>
        <thead>
            <tr>{"".join(f"<th>{col}</th>" for col in columns)}</tr>
        </thead>
        <tbody>
            {"".join("<tr>" + "".join(f"<td>{row.get(col, '')}</td>" for col in columns) + "</tr>" for row in records)}
        </tbody>
    </table>
    <div class="footer">Clothing Management System (CMS) Data Report</div>
</body>
</html>"""
        mem = io.BytesIO(html_content.encode("utf-8"))
        mem.seek(0)
        return send_file(
            mem,
            mimetype="text/html",
            as_attachment=True,
            download_name=f"cms_report_{session_id}.html"
        )

    return jsonify({"success": False, "message": "Unsupported format"}), 400